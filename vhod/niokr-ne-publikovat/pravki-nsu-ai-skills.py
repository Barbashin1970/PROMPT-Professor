#!/usr/bin/env python3
"""Правки ссылок в пакете NSU-AI-SKILLS после удаления двух образцов по беспилотнику.
Запускать в корне чистой копии пакета, ПОСЛЕ git filter-repo:

    python3 pravki-nsu-ai-skills.py

Каждая правка проверяет, что исходный текст найден ровно один раз; иначе — остановка без записи.
"""
import pathlib
import re
import sys

PRAVKI = [
    ("skills/niokr/primery/README.md",
     "Девятнадцать настоящих документов из **пяти областей** — программная инженерия,\n"
     "теплофизика, беспилотные аппараты, медицинская техника, методология вычислений.",
     "Семнадцать настоящих документов из **четырёх областей** — программная инженерия,\n"
     "теплофизика, медицинская техника, методология вычислений."),
    ("skills/niokr/primery/README.md",
     "Лабораторный макет тепловой сети, полунатурный\n"
     "стенд летательного аппарата и программный прогонщик замеров описываются по одним\n"
     "правилам, и видно, по каким.",
     "Лабораторный макет тепловой сети, комплекс для\n"
     "медицинского центра и программный прогонщик замеров описываются по одним правилам,\n"
     "и видно, по каким."),
    ("skills/niokr/references/stend-i-izmereniya.md",
     "  как описывается физический стенд;\n"
     "* `NIR-bespilotnik-stabilizaciya.md` — стенд полунатурного моделирования: то же,\n"
     "  но для летательного аппарата.",
     "  как описывается физический стенд."),
    ("skills/niokr/SKILL.md",
     "девятнадцать документов из пяти областей — отчёты\n"
     "о НИОКР, промежуточные отчёты этапов, технические задания на НИР и ОКР, проект\n"
     "договора с заданием,",
     "семнадцать документов из четырёх областей — отчёты\n"
     "о НИОКР, промежуточные отчёты этапов, технические задания на ОКР, проект\n"
     "договора с заданием на НИР,"),
    ("README.md",
     "и девятнадцать документов НИОКР из пяти областей науки",
     "и семнадцать документов НИОКР из четырёх областей науки"),
    ("README.md",
     "от программной инженерии до теплофизики,\n"
     "беспилотных аппаратов и медицинской техники.",
     "от программной инженерии до теплофизики\n"
     "и медицинской техники."),
]

teksty = {}
for put, staroe, novoe in PRAVKI:
    t = teksty.setdefault(put, pathlib.Path(put).read_text(encoding="utf-8"))
    if t.count(staroe) != 1:
        sys.exit(f"СТОП: в {put} не найден (или найден не один раз) текст:\n{staroe}\nНичего не записано.")
    teksty[put] = t.replace(staroe, novoe)

# строки таблицы образцов про два снятых файла
R = "skills/niokr/primery/README.md"
teksty[R], n = re.subn(r"^\| `(NIR-bespilotnik-stabilizaciya|TZ-NIR-bespilotnik)\.md` \|[^\n]*\n", "", teksty[R], flags=re.M)
if n != 2:
    sys.exit(f"СТОП: в таблице образцов найдено {n} строк про снятые файлы, ждали 2. Ничего не записано.")

for put, t in teksty.items():
    pathlib.Path(put).write_text(t, encoding="utf-8")
    print("✓", put)

ostalos = [str(p) for p in pathlib.Path(".").rglob("*.md")
           if ".git" not in p.parts and re.search(r"bespilotnik|беспилот|БПЛА|летательн", p.read_text(encoding="utf-8"))]
print("Упоминаний не осталось." if not ostalos else "Ещё упоминания в: " + ", ".join(ostalos))
